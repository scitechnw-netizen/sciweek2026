create or replace function public._token_hash(p_token text)
returns text
language sql
immutable
set search_path = public
as $$
  select encode(digest(coalesce(p_token,''), 'sha256'), 'hex');
$$;

create or replace function public._question_payload(
  p_question_id uuid,
  p_sign_number integer,
  p_sequence integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  q public.questions%rowtype;
begin
  select * into q from public.questions where id = p_question_id;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'question_not_found');
  end if;

  -- IMPORTANT: never return question_text or correct_option to the student browser.
  return jsonb_build_object(
    'ok', true,
    'question', jsonb_build_object(
      'signNumber', p_sign_number,
      'sequence', p_sequence,
      'choices', jsonb_build_array(
        jsonb_build_object('key','A','text',q.option_a),
        jsonb_build_object('key','B','text',q.option_b),
        jsonb_build_object('key','C','text',q.option_c),
        jsonb_build_object('key','D','text',q.option_d)
      )
    )
  );
end;
$$;

