create extension if not exists pgcrypto;

-- =========================
-- TABLES
-- =========================

create table if not exists public.students (
  id uuid primary key default gen_random_uuid(),
  student_code text not null unique,
  prefix text not null default '',
  first_name text not null,
  last_name text not null default '',
  class_name text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.questions (
  id uuid primary key default gen_random_uuid(),
  sign_number integer not null check (sign_number between 1 and 43),
  question_slot integer not null check (question_slot between 1 and 3),
  question_text text not null default '',
  option_a text not null default '',
  option_b text not null default '',
  option_c text not null default '',
  option_d text not null default '',
  correct_option text not null default 'A' check (correct_option in ('A','B','C','D')),
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(sign_number, question_slot)
);

create table if not exists public.game_sessions (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null unique references public.students(id) on delete cascade,
  session_token_hash text not null unique,
  status text not null default 'active' check (status in ('active','ended','completed')),
  correct_count integer not null default 0 check (correct_count between 0 and 25),
  wrong_count integer not null default 0 check (wrong_count >= 0),
  chests_opened integer not null default 0 check (chests_opened between 0 and 2),
  awaiting_chest boolean not null default false,
  current_question_id uuid references public.questions(id),
  current_sign_number integer check (current_sign_number between 1 and 43),
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  last_activity_at timestamptz not null default now()
);

create table if not exists public.game_answer_attempts (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.game_sessions(id) on delete cascade,
  question_id uuid not null references public.questions(id),
  sign_number integer not null check (sign_number between 1 and 43),
  selected_option text not null check (selected_option in ('A','B','C','D')),
  is_correct boolean not null,
  answered_at timestamptz not null default now()
);

create index if not exists idx_attempts_session on public.game_answer_attempts(session_id);
create index if not exists idx_attempts_session_sign on public.game_answer_attempts(session_id, sign_number);
create index if not exists idx_questions_active_sign on public.questions(is_active, sign_number);

-- Seed 43 signs x 3 question slots = 129 editable rows.
insert into public.questions (sign_number, question_slot)
select s.sign_number, q.question_slot
from generate_series(1,43) as s(sign_number)
cross join generate_series(1,3) as q(question_slot)
on conflict (sign_number, question_slot) do nothing;

